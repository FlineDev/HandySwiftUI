   }

   @Test(arguments: SFSymbol.allCases.map(\.rawValue))
   func preservesEnglishAliasesAndRawValue(rawValue: String) throws {
      let symbol = try #require(SFSymbol(rawValue: rawValue))
      let expected = try #require(Self.englishAliases[symbol.rawValue])
      let terms = symbol.searchTerms
      #expect(Array(terms.prefix(expected.count)) == expected)
      #expect(terms.contains(symbol.rawValue))
      #expect(terms.allSatisfy { $0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false })
      #expect(terms.contains("SFSymbol.searchTerms.\(symbol.rawValue)") == false)
      #expect(terms.contains("⚠️ missing") == false)
      #expect(Set(terms).count == terms.count)
   }

   @Test(.enabled(if: ProcessInfo.processInfo.environment["HANDYSWIFTUI_ALIAS_LANGUAGE"] != nil))
   func aliasesFollowLaunchLanguage() throws {
      let language = try #require(ProcessInfo.processInfo.environment["HANDYSWIFTUI_ALIAS_LANGUAGE"])
      try #require(["de", "en", "eo"].contains(language))
      try #require(Locale.preferredLanguages.first == language)
      try #require(Locale.current.identifier == "en_US")

      let terms = SFSymbol.airplane.searchTerms
      #expect(terms.contains("Flugzeug") == (language == "de"))
      #expect(terms.contains("airplane"))
      #expect(Array(terms.prefix(5)) == ["flight", "travel", "plane", "transportation", "journey"])
   }
